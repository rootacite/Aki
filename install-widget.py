#!/usr/bin/env python3
"""Install the Aki Plasma widget and its local WebSocket bridge."""

from __future__ import annotations

import argparse
import contextlib
import importlib.util
import json
import os
import secrets
import shutil
import socket
import subprocess
import sys
import tempfile
import time
from pathlib import Path

SERVICE_NAME = "akid-gui.service"
APPLET_ID = "org.acite.aki.chat"
DEFAULT_BRIDGE_PORT = 8765
DEFAULT_HOST = "127.0.0.1"


def service_unit(
    *,
    python_bin: str,
    repo: Path,
    socket_path: str,
    bridge_port: int,
    token_file: str,
    endpoint_file: str,
) -> str:
    return f"""[Unit]
Description=Aki GUI WebSocket bridge
After=network.target akid.service
Wants=akid.service

[Service]
Type=simple
ExecStart={python_bin} {repo / 'engine' / 'gui_bridge.py'}
WorkingDirectory={repo}
Environment="PYTHONUNBUFFERED=1"
Environment="AKI_SOCKET={socket_path}"
Environment="AKI_GUI_BRIDGE_HOST={DEFAULT_HOST}"
Environment="AKI_GUI_BRIDGE_PORT={bridge_port}"
Environment="AKI_GUI_TOKEN_FILE={token_file}"
Environment="AKI_GUI_ENDPOINT_FILE={endpoint_file}"
Restart=on-failure
RestartSec=2
TimeoutStopSec=10
UMask=0077

[Install]
WantedBy=default.target
"""


def bridge_config_js(*, port: int, token: str) -> str:
    return f""".pragma library
// Generated by install-widget.py. Do not commit a real token.
var host = "{DEFAULT_HOST}";
var port = {port};
var token = "{token}";
function url() {{
    return "ws://" + host + ":" + port + "/?token=" + encodeURIComponent(token);
}}
"""


def default_state_dir() -> Path:
    base = os.environ.get("XDG_DATA_HOME")
    root = Path(base).expanduser() if base else Path.home() / ".local" / "share"
    return root / "aki"


def default_socket_path() -> str:
    runtime = os.environ.get("XDG_RUNTIME_DIR")
    if runtime:
        return str(Path(runtime) / "aki" / "akid.sock")
    return f"/tmp/aki-{os.getuid()}/akid.sock"


def _write_private(path: Path, text: str) -> None:
    path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write(text)
        handle.flush()
        os.fsync(handle.fileno())
    os.chmod(path, 0o600)


def ensure_token(path: Path) -> str:
    try:
        value = path.read_text("utf-8").strip()
    except FileNotFoundError:
        value = ""
    if value:
        return value
    token = secrets.token_urlsafe(32)
    _write_private(path, token + "\n")
    return token


def run(command: list[str], *, check: bool = True) -> subprocess.CompletedProcess[str]:
    return subprocess.run(command, text=True, capture_output=True, check=check)


def applet_installed(*, packageroot: Path | None = None) -> bool:
    command = ["kpackagetool6", "--type", "Plasma/Applet", "--list"]
    if packageroot is not None:
        command.extend(["--packageroot", str(packageroot)])
    try:
        result = run(command, check=False)
    except FileNotFoundError:
        return False
    return result.returncode == 0 and APPLET_ID in result.stdout


def install_applet(
    repo: Path,
    *,
    token: str,
    bridge_port: int,
    packageroot: Path | None = None,
) -> None:
    source = repo / "kde-widget" / APPLET_ID
    if not source.is_dir():
        raise RuntimeError(f"widget package not found: {source}")
    avatar = repo / "aki_avi.jpg"
    if not avatar.is_file():
        raise RuntimeError(f"avatar file not found: {avatar}")
    with tempfile.TemporaryDirectory(prefix="aki-widget-") as temporary:
        staging = Path(temporary) / APPLET_ID
        shutil.copytree(source, staging)
        images = staging / "contents" / "images"
        images.mkdir(parents=True, exist_ok=True)
        shutil.copy2(avatar, images / "aki_avi.jpg")
        config = staging / "contents" / "config" / "bridge-config.js"
        config.parent.mkdir(parents=True, exist_ok=True)
        _write_private(config, bridge_config_js(port=bridge_port, token=token))
        command = ["kpackagetool6", "--type", "Plasma/Applet"]
        if packageroot is not None:
            command.extend(["--packageroot", str(packageroot)])
        if applet_installed(packageroot=packageroot):
            command.extend(["--upgrade", str(staging)])
        else:
            command.extend(["--install", str(staging)])
        try:
            run(command)
        except subprocess.CalledProcessError as exc:
            raise RuntimeError((exc.stderr or exc.stdout or str(exc)).strip()) from exc


def uninstall_applet(*, packageroot: Path | None = None) -> None:
    command = ["kpackagetool6", "--type", "Plasma/Applet", "--remove", APPLET_ID]
    if packageroot is not None:
        command.extend(["--packageroot", str(packageroot)])
    with contextlib.suppress(FileNotFoundError, subprocess.CalledProcessError):
        run(command, check=False)


def port_is_open(host: str, port: int, timeout: float = 0.4) -> bool:
    try:
        with socket.create_connection((host, port), timeout=timeout):
            return True
    except OSError:
        return False


def wait_bridge(
    *,
    port: int,
    endpoint_file: Path,
    timeout: float = 10.0,
) -> bool:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if endpoint_file.exists() and port_is_open(DEFAULT_HOST, port):
            return True
        time.sleep(0.2)
    return False


def status(*, unit_path: Path, endpoint_file: Path, packageroot: Path | None) -> int:
    print(f"unit: {unit_path}")
    try:
        result = run(["systemctl", "--user", "is-active", SERVICE_NAME], check=False)
        print(f"service: {result.stdout.strip() or result.stderr.strip()}")
    except FileNotFoundError:
        print("service: systemctl unavailable")
    if endpoint_file.exists():
        try:
            data = json.loads(endpoint_file.read_text("utf-8"))
            print(
                "bridge: "
                + json.dumps(
                    {key: data.get(key) for key in ("host", "port")},
                    ensure_ascii=False,
                )
            )
        except (OSError, ValueError):
            print("bridge: endpoint file is invalid")
    else:
        print("bridge: endpoint file missing")
    print(f"applet installed: {applet_installed(packageroot=packageroot)}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Install the Aki Plasma widget")
    parser.add_argument("--dry-run", action="store_true", help="print actions only")
    parser.add_argument("--status", action="store_true")
    parser.add_argument("--uninstall", action="store_true")
    parser.add_argument("--bridge-port", type=int, default=DEFAULT_BRIDGE_PORT)
    parser.add_argument("--socket", default=default_socket_path())
    parser.add_argument("--token-file")
    parser.add_argument("--endpoint-file")
    parser.add_argument("--packageroot", help="alternate kpackagetool6 package root")
    parser.add_argument("--restart-plasmashell", action="store_true")
    args = parser.parse_args(argv)

    if os.geteuid() == 0:
        print("refusing to install a per-user widget as root", file=sys.stderr)
        return 2

    repo = Path(__file__).resolve().parent
    state_dir = default_state_dir()
    token_file = Path(args.token_file).expanduser() if args.token_file else state_dir / "gui-token"
    endpoint_file = (
        Path(args.endpoint_file).expanduser()
        if args.endpoint_file
        else state_dir / "gui-bridge.json"
    )
    packageroot = Path(args.packageroot).expanduser() if args.packageroot else None
    unit_path = Path.home() / ".config" / "systemd" / "user" / SERVICE_NAME

    if args.status:
        return status(unit_path=unit_path, endpoint_file=endpoint_file, packageroot=packageroot)

    if args.uninstall:
        with contextlib.suppress(FileNotFoundError):
            run(["systemctl", "--user", "disable", "--now", SERVICE_NAME], check=False)
        if unit_path.exists():
            unit_path.unlink()
        with contextlib.suppress(FileNotFoundError):
            run(["systemctl", "--user", "daemon-reload"], check=False)
        uninstall_applet(packageroot=packageroot)
        for path in (token_file, endpoint_file):
            with contextlib.suppress(OSError):
                path.unlink()
        print("Aki widget and GUI bridge removed; akid, MemFS and history were left untouched")
        return 0

    if importlib.util.find_spec("websockets") is None:
        print("Python package 'websockets' is required for the GUI bridge", file=sys.stderr)
        return 1
    if shutil.which("kpackagetool6") is None:
        print("kpackagetool6 is required to install the Plasma widget", file=sys.stderr)
        return 1

    python_bin = "/usr/bin/python3" if Path("/usr/bin/python3").exists() else sys.executable
    unit = service_unit(
        python_bin=python_bin,
        repo=repo,
        socket_path=args.socket,
        bridge_port=args.bridge_port,
        token_file=str(token_file),
        endpoint_file=str(endpoint_file),
    )

    if args.dry_run:
        print(f"# widget source: {repo / 'kde-widget' / APPLET_ID}")
        print(f"# packageroot: {packageroot or 'user default'}")
        print(f"# bridge port: {args.bridge_port}")
        print(f"# token file: {token_file}")
        print(f"# endpoint file: {endpoint_file}")
        print(f"# would write {unit_path}")
        print(unit, end="")
        return 0

    was_installed = applet_installed(packageroot=packageroot)
    token = ensure_token(token_file)
    install_applet(
        repo,
        token=token,
        bridge_port=args.bridge_port,
        packageroot=packageroot,
    )

    unit_path.parent.mkdir(parents=True, exist_ok=True)
    unit_path.write_text(unit, encoding="utf-8")
    os.chmod(unit_path, 0o644)
    try:
        run(["systemctl", "--user", "daemon-reload"])
        run(["systemctl", "--user", "enable", "--now", SERVICE_NAME])
        run(["systemctl", "--user", "restart", SERVICE_NAME])
    except FileNotFoundError:
        print("systemctl is unavailable; bridge unit installed but not started", file=sys.stderr)
        return 1
    except subprocess.CalledProcessError as exc:
        print(f"cannot start {SERVICE_NAME}: {exc.stderr or exc}", file=sys.stderr)
        return 1

    if not wait_bridge(port=args.bridge_port, endpoint_file=endpoint_file):
        print(
            f"GUI bridge did not become ready; inspect with "
            f"journalctl --user -u {SERVICE_NAME} -n 100 --no-pager",
            file=sys.stderr,
        )
        return 1
    if args.restart_plasmashell:
        try:
            run(["systemctl", "--user", "restart", "plasma-plasmashell.service"])
            print("plasmashell restarted")
        except (FileNotFoundError, subprocess.CalledProcessError) as exc:
            print(f"warning: cannot restart plasmashell: {exc}", file=sys.stderr)
    elif was_installed:
        print(
            "widget was upgraded; run "
            "`systemctl --user restart plasma-plasmashell.service` to reload QML"
        )
    print(f"Aki widget installed: {APPLET_ID}")
    print("Add it with: right-click the bottom panel -> Add Widgets -> search for Aki")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
